// Calendar-day selection uses Riyadh midnight, not the device timezone. No fabricated quotations.
export function dailyTechQuestions(now:Date,count=6){
 const date=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Riyadh',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(now);
 const part=(name:string)=>Number(date.find(p=>p.type===name)?.value);
 const day=Math.floor(Date.UTC(part('year'),part('month')-1,part('day'))/86400000);
 return Array.from({length:Math.min(count,techQuestions.length)},(_,i)=>techQuestions[(day*6+i)%techQuestions.length]);
}
