export function techEntryForDay(now: Date): TechEntry {
  const day = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Riyadh",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(now);
  const get = (type: string) => day.find((p) => p.type === type)?.value || "0";
  const serial = Math.floor(
    Date.UTC(
      Number(get("year")),
      Number(get("month")) - 1,
      Number(get("day")),
    ) / 86400000,
  );
  return techEntries[
    (((serial * 37) % techEntries.length) + techEntries.length) %
      techEntries.length
  ];
}
